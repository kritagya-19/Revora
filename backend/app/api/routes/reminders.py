from fastapi import APIRouter, HTTPException, Query
from typing import List, Optional
from app.models.schemas import (
    DynamicReminder,
    ReminderEvaluationResult,
    CreateReminderRequest,
    UpdateReminderRequest,
    DismissReminderRequest,
    ReminderStatus
)
from app.services.reminder_repository import reminder_repo
from app.services.reminder_service import reminder_service

router = APIRouter()

@router.get("", response_model=List[DynamicReminder])
def list_reminders(
    account_id: Optional[str] = Query(None, description="Filter reminders by account ID"),
    status: Optional[str] = Query(None, description="Filter reminders by status (active, completed, dismissed, snoozed)"),
    reminder_type: Optional[str] = Query(None, description="Filter by reminder type"),
    severity: Optional[str] = Query(None, description="Filter by severity (critical, high, medium, low)")
):
    """
    GET /api/reminders
    Returns dynamic reminders generated by the early warning and continuous improvement engine.
    """
    return reminder_repo.get_all(
        account_id=account_id,
        status=status,
        reminder_type=reminder_type,
        severity=severity
    )

@router.post("/evaluate", response_model=ReminderEvaluationResult)
def evaluate_reminders():
    """
    POST /api/reminders/evaluate
    Scans portfolio accounts against configured conditions (usage drops, touchpoint inactivity,
    overdue follow-up tasks, unresolved feedback blockers, upcoming renewals) and triggers reminders.
    Enforces deduplication guards against active reminders for the same unresolved issue.
    """
    try:
        return reminder_service.evaluate_portfolio_reminders()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Reminder evaluation failed: {e}")

@router.get("/{reminder_id}", response_model=DynamicReminder)
def get_reminder(reminder_id: str):
    """
    GET /api/reminders/{reminder_id}
    Retrieves a single reminder by ID.
    """
    r = reminder_repo.get_by_id(reminder_id)
    if not r:
        raise HTTPException(status_code=404, detail=f"Reminder {reminder_id} not found")
    return r

@router.post("", response_model=DynamicReminder, status_code=201)
def create_custom_reminder(req: CreateReminderRequest):
    """
    POST /api/reminders
    Manually creates a new reminder for an account.
    """
    try:
        return reminder_service.create_custom_reminder(req)
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Failed to create reminder: {e}")

@router.patch("/{reminder_id}", response_model=DynamicReminder)
def update_reminder(reminder_id: str, req: UpdateReminderRequest):
    """
    PATCH /api/reminders/{reminder_id}
    Updates status, priority, or due date for a reminder.
    """
    r = reminder_repo.get_by_id(reminder_id)
    if not r:
        raise HTTPException(status_code=404, detail=f"Reminder {reminder_id} not found")

    if req.status is not None:
        r.status = req.status
    if req.title is not None:
        r.title = req.title
    if req.description is not None:
        r.description = req.description
    if req.severity is not None:
        r.severity = req.severity
    if req.due_date is not None:
        r.due_date = req.due_date
    if req.dismissed_reason is not None:
        r.dismissed_reason = req.dismissed_reason

    return reminder_repo.save_reminder(r)

@router.post("/{reminder_id}/complete", response_model=DynamicReminder)
def complete_reminder(reminder_id: str):
    """
    POST /api/reminders/{reminder_id}/complete
    Marks a reminder as completed.
    """
    r = reminder_service.complete_reminder(reminder_id)
    if not r:
        raise HTTPException(status_code=404, detail=f"Reminder {reminder_id} not found")
    return r

@router.post("/{reminder_id}/dismiss", response_model=DynamicReminder)
def dismiss_reminder(reminder_id: str, req: DismissReminderRequest):
    """
    POST /api/reminders/{reminder_id}/dismiss
    Dismisses a reminder with a reason to prevent frequency fatigue.
    """
    r = reminder_service.dismiss_reminder(reminder_id, reason=req.reason or "Dismissed by user")
    if not r:
        raise HTTPException(status_code=404, detail=f"Reminder {reminder_id} not found")
    return r
